const fs = require("node:fs");
const path = require("node:path");

const configDir = path.join(__dirname, "../config");
const source = fs.readFileSync(path.join(configDir, "clash-party-ct-uk.js"), "utf8");
const output = path.join(configDir, "clash-party-ufi2.js");
const marker = "const useSecondUfi = false;";
if (source.split(marker).length !== 2) throw new Error("Expected one UFI selector");

const generated = "// Generated by scripts/build_clash_ufi2.js.\n" +
  source.replace(marker, "const useSecondUfi = true;");

if (process.argv.includes("--check")) {
  if (fs.readFileSync(output, "utf8") !== generated) {
    throw new Error("Rebuild the UFI 2 override with node scripts/build_clash_ufi2.js");
  }
} else {
  fs.writeFileSync(output, generated);
}
